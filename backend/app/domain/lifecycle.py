TRANSITIONS = {
    'DISCOVERED': {'METRICS_PENDING', 'FILTERED', 'RIGHTS_REVIEW', 'ELIGIBLE', 'SKIPPED'},
    'METRICS_PENDING': {'FILTERED', 'RIGHTS_REVIEW', 'ELIGIBLE', 'SKIPPED'},
    'FILTERED': {'RIGHTS_REVIEW', 'ELIGIBLE', 'SKIPPED'},
    'RIGHTS_REVIEW': {'ELIGIBLE', 'SKIPPED', 'CANCELLED'},
    'ELIGIBLE': {'DOWNLOADING', 'WAITING_APPROVAL', 'SCHEDULED', 'CANCELLED'},
    'DOWNLOADING': {'PROCESSING', 'READY', 'FAILED', 'CANCELLED'},
    'PROCESSING': {'READY', 'FAILED', 'CANCELLED'},
    'READY': {'WAITING_APPROVAL', 'SCHEDULED', 'UPLOADING', 'CANCELLED'},
    'WAITING_APPROVAL': {'SCHEDULED', 'READY', 'CANCELLED'},
    'SCHEDULED': {'DOWNLOADING', 'READY', 'UPLOADING', 'CANCELLED'},
    'UPLOADING': {'PLATFORM_PROCESSING', 'RECONCILIATION_REQUIRED', 'FAILED'},
    'PLATFORM_PROCESSING': {'PUBLISHED', 'DRAFT_CREATED', 'FAILED', 'RECONCILIATION_REQUIRED'},
    'RECONCILIATION_REQUIRED': {'PLATFORM_PROCESSING', 'PUBLISHED', 'DRAFT_CREATED', 'FAILED'},
    'FAILED': {'SCHEDULED', 'CANCELLED'},
    'PUBLISHED': set(), 'DRAFT_CREATED': set(), 'CANCELLED': set(), 'SKIPPED': set(),
}


def transition(current: str, target: str):
    if target not in TRANSITIONS.get(current, set()):
        raise ValueError(f'Invalid transition {current} → {target}')
    return target
